# Tier: F
"""Generates the UE-free C++ data headers of the demo from the JSON sources, so C++ never parses JSON
and the numbers cannot drift from the files:

  UE5Project/Plugins/DronePhysicsBridge/Source/DronePhysicsBridge/Public/Generated/DroneReferenceBuild.h
      from offline_pipeline/components/catalog.json, offline_pipeline/props/apce_12x6.json
  UE5Project/Plugins/DronePhysicsBridge/Source/DronePhysicsBridge/Public/Generated/DroneEnvironmentsGenerated.h
      from UE5Project/Plugins/DronePhysicsBridge/Content/DroneEnvironments.json

Run from the repo root:  python tools/gen_demo_headers.py          (writes)
                         python tools/gen_demo_headers.py --check  (exit 1 if a file is out of date; CI)
Every item keeps its CITED / ASSUMED status so the report can print it.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "UE5Project" / "Plugins" / "DronePhysicsBridge"
OUT_DIR = PLUGIN / "Source" / "DronePhysicsBridge" / "Public" / "Generated"
CATALOG = ROOT / "offline_pipeline" / "components" / "catalog.json"
PROP = ROOT / "offline_pipeline" / "props" / "apce_12x6.json"
ENVS = PLUGIN / "Content" / "DroneEnvironments.json"


def camel(text: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[_\W]+", text) if p)


def cpp_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v: float) -> str:
    return repr(float(v))


def axial_run(prop: dict) -> tuple[float, list[tuple[float, float]]]:
    """The wind-tunnel run closest to 4000 RPM (hover is about 3600 RPM) as strictly increasing (J, Ct) rows."""
    best = None
    for name, rows in prop["wind_tunnel"].items():
        m = re.search(r"_(\d+)\.txt$", name)
        if not m:
            continue
        rpm = float(m.group(1))
        if best is None or abs(rpm - 4000.0) < abs(best[0] - 4000.0):
            best = (rpm, rows)
    if best is None:
        raise ValueError("no wind-tunnel run in the propeller json")
    pts: list[tuple[float, float]] = []
    for r in best[1]:
        if not pts or r["j"] > pts[-1][0]:
            pts.append((r["j"], r["ct"]))
    return best[0], pts


def reference_header(cat: dict, prop: dict) -> str:
    lines = [
        "// Tier: V",
        "// GENERATED by tools/gen_demo_headers.py from offline_pipeline/components/catalog.json and",
        "// offline_pipeline/props/apce_12x6.json. DO NOT EDIT. Every value is CITED or ASSUMED (see kItems);",
        "// nothing here is validated against hardware. UE-free (no includes beyond <cstddef>).",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace DroneRef",
        "{",
        "struct Item",
        "{",
        "    const char* Name;    // group.key in catalog.json",
        "    const char* Value;   // text, so arrays and numbers print the same way",
        "    const char* Unit;",
        "    const char* Status;  // CITED or ASSUMED",
        "    const char* Source;",
        "};",
        "",
    ]
    items = []
    for group, entries in cat.items():
        if group.startswith("_"):
            continue
        for key, item in entries.items():
            if not (isinstance(item, dict) and "value" in item):
                continue
            v = item["value"]
            name = f"{group}.{key}"
            items.append((name, json.dumps(v) if isinstance(v, list) else str(v), item["unit"], item["status"], item["source"]))
            if isinstance(v, (int, float)) and not isinstance(v, bool):
                lines.append(f"constexpr double k{camel(group)}{camel(key)} = {num(v)};  // {item['status']}")
    lines += ["", "// APC Thin Electric 12x6 (UIUC volume 4), static fit over the hover band: CITED data, ASSUMED band.",
              f"constexpr double kPropCt = {num(prop['static_fit']['ct'])};",
              f"constexpr double kPropCp = {num(prop['static_fit']['cp'])};",
              f"constexpr double kPropKappaM = {num(prop['static_fit']['kappa_m'])};",
              f"constexpr double kPropFitBandLoRpm = {num(prop['static_fit']['band_rpm'][0])};",
              f"constexpr double kPropFitBandHiRpm = {num(prop['static_fit']['band_rpm'][1])};",
              f"constexpr double kPropWindTunnelMaxRpm = 6044.0;  // above this the data is extrapolated",
              "",
              "// Ct(J) of the UIUC wind-tunnel run closest to 4000 RPM (axial flow, CITED data): used ONLY by the report to show how",
              "// much thrust the core's constant static Ct overstates in a climb. J = V_axial / (n D), n in rev/s.",
              f"constexpr double kPropAxialRunRpm = {num(axial_run(prop)[0])};",
              f"constexpr std::size_t kPropAxialCount = {len(axial_run(prop)[1])};",
              "constexpr double kPropAxialJ[] = {" + ", ".join(num(j) for j, _ in axial_run(prop)[1]) + "};",
              "constexpr double kPropAxialCt[] = {" + ", ".join(num(c) for _, c in axial_run(prop)[1]) + "};",
              "", "constexpr Item kItems[] = {"]
    for name, value, unit, status, source in items:
        lines.append(f"    {{{cpp_str(name)}, {cpp_str(value)}, {cpp_str(unit)}, {cpp_str(status)}, {cpp_str(source)}}},")
    lines += ["};", "constexpr std::size_t kItemCount = sizeof(kItems) / sizeof(kItems[0]);",
              f"constexpr const char* kPropCitation = {cpp_str(prop['citation'])};", "}  // namespace DroneRef", ""]
    return "\n".join(lines)


def environments_header(envs: dict) -> str:
    lines = [
        "// Tier: V",
        "// GENERATED by tools/gen_demo_headers.py from DroneEnvironments.json. DO NOT EDIT. Every number is ASSUMED",
        "// (typical climate for the name; TODO(HUMAN-VERIFY: demo value)). UE-free.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace DroneEnvTable",
        "{",
        "struct Row",
        "{",
        "    const char* Id;",
        "    const char* Name;",
        "    double SiteAltitudeM;",
        "    double AmbientTempC;",
        "    double HumidityPct;",
        "    double WindSpeedMps;",
        "    double WindTowardDeg;",
        "    double GustSigmaMps;",
        "};",
        "",
        "constexpr Row kRows[] = {",
    ]
    for e in envs["environments"]:
        lines.append(f"    {{{cpp_str(e['id'])}, {cpp_str(e['name'])}, {num(e['site_altitude_m'])}, {num(e['ambient_temp_c'])}, "
                     f"{num(e['humidity_pct'])}, {num(e['wind_speed_mps'])}, {num(e['wind_toward_deg'])}, {num(e['gust_sigma_mps'])}}},")
    lines += ["};", "constexpr std::size_t kRowCount = sizeof(kRows) / sizeof(kRows[0]);", "}  // namespace DroneEnvTable", ""]
    return "\n".join(lines)


def render_all() -> dict[Path, str]:
    cat = json.loads(CATALOG.read_text())
    prop = json.loads(PROP.read_text())
    envs = json.loads(ENVS.read_text())
    return {OUT_DIR / "DroneReferenceBuild.h": reference_header(cat, prop),
            OUT_DIR / "DroneEnvironmentsGenerated.h": environments_header(envs)}


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in render_all().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path}")
    if stale:
        print("out of date (run python tools/gen_demo_headers.py): " + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
