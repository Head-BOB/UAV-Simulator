# Tier: F
"""Writes tools/package/helpers_lock.txt: the part of offline_pipeline/requirements.txt (the hash-locked set) that the packaged helper
programs need, copied VERBATIM (same pins, same hashes). It adds no version and no hash of its own.

The helpers (tools/parts, tools/report) import one third-party package, jsonschema (tools/parts/partsdb.py). The set is jsonschema and
everything the main lock says it pulls in (its "# via" annotations, followed transitively). Anything else in the main lock (numpy, onnx,
scikit-learn ...) is for the offline pipeline and stays out of the package.

Usage: python tools/package/make_helpers_lock.py [--check]
  --check  fail if helpers_lock.txt is not exactly what this script would write (CI).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAIN_LOCK = ROOT / "offline_pipeline" / "requirements.txt"
OUT = Path(__file__).resolve().parent / "helpers_lock.txt"
ROOT_PACKAGES = ("jsonschema",)
HEADER = ("# Hash-locked packages the packaged helper programs need. Generated by tools/package/make_helpers_lock.py from\n"
          "# offline_pipeline/requirements.txt: every block below is a verbatim copy (same pin, same hashes). Do not edit by hand.\n")


class LockError(ValueError):
    """The main lock is not in the expected pip-compile format or a root package is missing."""


def parse_blocks(text: str) -> dict[str, str]:
    """name -> verbatim block text (requirement line, hash lines, via comment), in file order."""
    blocks: dict[str, str] = {}
    cur_name, cur = None, []
    for line in text.splitlines(keepends=True):
        m = re.match(r"^([A-Za-z0-9_.\-]+)==\S+", line)
        if m:
            if cur_name:
                blocks[cur_name] = "".join(cur)
            cur_name, cur = m.group(1).lower(), [line]
        elif cur_name is not None:
            cur.append(line)
    if cur_name:
        blocks[cur_name] = "".join(cur)
    return blocks


def via_of(block: str) -> set[str]:
    """Package names listed in the block's '# via' comment (a '-r ...' source is not a package)."""
    names: set[str] = set()
    on = False
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("# via"):
            on = True
            rest = s[len("# via"):].strip()
            if rest and not rest.startswith("-r"):
                names.add(rest.lower())
        elif on and s.startswith("#"):
            item = s.lstrip("#").strip()
            if item and not item.startswith("-r"):
                names.add(item.lower())
        elif on:
            on = False
    return names


def closure(blocks: dict[str, str], roots=ROOT_PACKAGES) -> list[str]:
    for r in roots:
        if r not in blocks:
            raise LockError(f"{r} is not in the main lock")
    chosen = set(roots)
    changed = True
    while changed:
        changed = False
        for name, block in blocks.items():
            if name not in chosen and via_of(block) & chosen:
                chosen.add(name)
                changed = True
    return [n for n in blocks if n in chosen]   # main-lock order


def render(main_text: str) -> str:
    blocks = parse_blocks(main_text)
    return HEADER + "".join(blocks[n] for n in closure(blocks))


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        text = render(MAIN_LOCK.read_text(encoding="utf-8"))
    except (OSError, LockError) as e:
        print(f"LOCK STOPPED: {e}", file=sys.stderr)
        return 1
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("helpers_lock.txt is stale: run tools/package/make_helpers_lock.py", file=sys.stderr)
            return 2
        print("helpers lock is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(parse_blocks(text))} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
